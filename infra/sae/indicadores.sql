CREATE VIEW FLUCITO_SAE_CORTE_FACTURACION (HUELLA, DESDE, HASTA) AS
SELECT CAST('@SHA256@' AS CHAR(64)), CAST(MIN(FECHA_DOC) AS DATE), CAST(MAX(FECHA_DOC) AS DATE)
FROM FACTF02;

CREATE VIEW FLUCITO_SAE_FACTURACION_DIA (FECHA, TIPO, MONEDA, DOCUMENTOS, CON_IMPORTE, IMPORTE) AS
SELECT CAST(D.FECHA_DOC AS DATE), D.TIPO, TRIM(M.CVE_MONED), COUNT(*), COUNT(D.IMPORTE), SUM(D.IMPORTE)
FROM (
    SELECT F.FECHA_DOC, CAST('F' AS CHAR(1)) AS TIPO, F.NUM_MONED,
           CASE WHEN F.TIPCAMB > 0 THEN CAST(F.IMPORTE / F.TIPCAMB AS DECIMAL(18, 2)) END AS IMPORTE
    FROM FACTF02 F WHERE F.STATUS IN ('E','O') AND F.FECHA_DOC IS NOT NULL
    UNION ALL
    SELECT D.FECHA_DOC, CAST('D' AS CHAR(1)), D.NUM_MONED,
           CASE WHEN D.TIPCAMB > 0 THEN CAST(D.IMPORTE / D.TIPCAMB AS DECIMAL(18, 2)) END
    FROM FACTD02 D WHERE D.STATUS IN ('E','O') AND D.FECHA_DOC IS NOT NULL
) D LEFT JOIN MONED02 M ON M.NUM_MONED = D.NUM_MONED
GROUP BY 1, 2, 3;

CREATE VIEW FLUCITO_SAE_CORTE_INVENTARIO (HUELLA, ULTIMO_MOVIMIENTO) AS
SELECT CAST('@SHA256@' AS CHAR(64)), CAST(MAX(FECHA_DOCU) AS DATE) FROM MINVE02;

CREATE VIEW FLUCITO_SAE_ALMACENES (CLAVE, NOMBRE) AS
SELECT CVE_ALM, TRIM(DESCR) FROM ALMACENES02 WHERE STATUS = 'A';

-- La clave original enlaza cada producto con su almacén. Aplicar TRIM alteraría su identidad.
CREATE VIEW FLUCITO_SAE_INVENTARIO (ALMACEN, CLAVE, NOMBRE, UNIDAD, EXISTENCIA, MINIMO) AS
SELECT CAST(NULL AS INTEGER), I.CVE_ART, TRIM(I.DESCR), TRIM(I.UNI_MED),
       CAST(I.EXIST AS DECIMAL(18, 6)), CAST(I.STOCK_MIN AS DECIMAL(18, 6))
FROM INVE02 I WHERE I.STATUS = 'A' AND I.TIPO_ELE = 'P'
UNION ALL
SELECT A.CLAVE, I.CVE_ART, TRIM(I.DESCR), TRIM(I.UNI_MED),
       CAST(M.EXIST AS DECIMAL(18, 6)), CAST(M.STOCK_MIN AS DECIMAL(18, 6))
FROM MULT02 M
JOIN INVE02 I ON I.CVE_ART = M.CVE_ART
JOIN FLUCITO_SAE_ALMACENES A ON A.CLAVE = M.CVE_ALM
WHERE I.STATUS = 'A' AND I.TIPO_ELE = 'P' AND M.STATUS = 'A';

