CREATE VIEW FLUCITO_SAE_CORTE_COMPRAS (HUELLA, DESDE, HASTA) AS
SELECT CAST('@SHA256@' AS CHAR(64)),
       CAST(MIN(FECHA_DOC) AS DATE),
       CAST(MAX(FECHA_DOC) AS DATE)
FROM COMPC02;

-- IMPORTE está en moneda base. Recuperamos el importe del documento antes de sumar.
CREATE VIEW FLUCITO_SAE_COMPRAS_DIA (
    FECHA, MONEDA, PROVEEDOR_CLAVE, PROVEEDOR_NOMBRE, DOCUMENTOS, CON_IMPORTE, IMPORTE
) AS
SELECT COMPRA.FECHA, COMPRA.MONEDA, COMPRA.PROVEEDOR_CLAVE, COMPRA.PROVEEDOR_NOMBRE,
       COUNT(*), COUNT(COMPRA.IMPORTE), SUM(COMPRA.IMPORTE)
FROM (
    SELECT CAST(C.FECHA_DOC AS DATE) AS FECHA,
           TRIM(M.CVE_MONED) AS MONEDA,
           TRIM(C.CVE_CLPV) AS PROVEEDOR_CLAVE,
           NULLIF(TRIM(P.NOMBRE), '') AS PROVEEDOR_NOMBRE,
           CASE
               WHEN C.TIPCAMB > 0 THEN CAST(C.IMPORTE / C.TIPCAMB AS DECIMAL(18, 2))
           END AS IMPORTE
    FROM COMPC02 C
    LEFT JOIN MONED02 M ON M.NUM_MONED = C.NUM_MONED
    LEFT JOIN PROV02 P ON P.CLAVE = C.CVE_CLPV
    WHERE C.STATUS IN ('E', 'O') AND C.FECHA_DOC IS NOT NULL
) COMPRA
GROUP BY 1, 2, 3, 4;

GRANT SELECT ON FLUCITO_SAE_CORTE_COMPRAS TO USER FLUCITO_SAE_LECTOR;
GRANT SELECT ON FLUCITO_SAE_COMPRAS_DIA TO USER FLUCITO_SAE_LECTOR;
COMMIT;
